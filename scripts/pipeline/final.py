COMMON_SUBJ = {"음악", "미술", "체육"}


def find(grade, subj, kw):
    segs = [(k, t) for k, t in SEG if k[0] == grade and k[2] == subj]
    hit = [k for k, _ in segs if kw in k[3]]
    if hit:
        return hit[0]
    hit = [k for k, t in segs if kw in t]
    if not hit:
        raise SystemExit(f"보정 키워드를 찾지 못함: {grade}학년 {subj} '{kw}'")
    k = hit[0]
    return (k[0], k[1], k[2], k[3] if " › " in k[3] else f"{k[3]} › {kw} 관련 차시")


out = []
for s in STD:
    if s["교과"] not in SUBJ:
        continue
    code = s["코드"].strip("[]")
    cand = [(k, t) for k, t in SEG if k[2] == s["교과"] and BAND[k[0]] == s["학년군"]]
    q = vec.transform([s["성취기준"]])
    sims = cosine_similarity(q, vec.transform([t for _, t in cand]))[0] + 0.6 * cosine_similarity(
        q, vec.transform([re.sub(r"^[\d.\s]+|독서단원:|독서:", "", k[3]) for k, _ in cand]))[0]
    ranked = sorted(zip(sims, [k for k, _ in cand]), key=lambda x: -x[0])
    bestg = {}
    for sc, k in ranked:
        bestg.setdefault(k[0], (float(sc), k))
    gs = sorted(bestg.values(), key=lambda x: -x[0])
    rec = {"학년군": s["학년군"], "교과": s["교과"], "영역번호": s["영역번호"], "영역": s["영역"], "코드": s["코드"], "성취기준": s["성취기준"]}
    if code in O:
        if O[code] == U:
            place, how = [], "미배치"
        else:
            place, how = [find(g, s["교과"], kw) for g, kw in O[code]], "검토 보정"
    elif s["교과"] == "체육":
        n = s["영역번호"]
        place = [k for k, _ in SEG if k[2] == "체육" and BAND[k[0]] == s["학년군"] and k[3].startswith(f"{n}. ")]
        how = "영역 대단원"
    elif s["교과"] in COMMON_SUBJ:
        place, how = [k for _, k in sorted(gs, key=lambda x: x[1][0])], "자동 대조"
    elif gs[0][0] < 0.15:
        place, how = [], "미배치"
    else:
        place = [gs[0][1]]
        if len(gs) > 1 and gs[1][0] >= 0.25 and gs[1][0] >= 0.85 * gs[0][0]:
            place.append(gs[1][1])
        how = "자동 대조"
    place = sorted(dict.fromkeys(place), key=lambda k: (k[0], k[1]))
    grades = sorted({k[0] for k in place})
    if not place:
        kind = "5·6학년 2학기 단원 예상 (계획서 미제출)" if s["학년군"] == "5~6학년군" else "계획서에서 단원을 찾지 못함"
    elif s["교과"] in COMMON_SUBJ:
        kind = "두 학년 반복·심화"
    elif len(grades) > 1:
        kind = "두 학년 공통"
    else:
        kind = f"{grades[0]}학년"
    rec.update(배치=[{"학년": k[0], "학기": k[1], "단원": k[3]} for k in place], 구분=kind, 근거=how)
    out.append(rec)
